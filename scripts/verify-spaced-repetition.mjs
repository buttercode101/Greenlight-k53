import assert from "node:assert/strict";
import "../assets/spaced-repetition.js";
const sm2 = globalThis.GreenLightSM2;
assert.ok(sm2, "SM-2 API is exposed");
const state = {};
const q = { id: "sign:R1", q: "What does STOP mean?", opts: ["Stop", "Go"], ans: 0, ex: "Stop fully.", topic: "Signs and signals", code: "2" };
const t0 = Date.UTC(2026, 0, 1);
let row = sm2.recordAnswer(state, q, false, t0, "event-1");
assert.equal(row.interval, 1);
assert.equal(row.repetitions, 0);
assert.ok(row.easeFactor < 2.5, "incorrect recall lowers the SM-2 ease factor");
assert.equal(row.nextReview, t0 + sm2.DAY);
assert.equal(sm2.recordAnswer(state, q, false, t0, "event-1").attempts, 1, "duplicate event is idempotent");
row = sm2.recordAnswer(state, q, true, t0 + sm2.DAY, "event-2");
assert.equal(row.interval, 1);
assert.equal(row.repetitions, 1);
assert.ok(row.easeFactor > 1.96, "correct recall raises the SM-2 ease factor");
row = sm2.recordAnswer(state, q, true, t0 + 2 * sm2.DAY, "event-3");
assert.equal(row.interval, 6);
assert.equal(row.repetitions, 2);
row = sm2.recordAnswer(state, q, true, t0 + 8 * sm2.DAY, "event-4");
assert.ok(row.interval <= 21);
assert.equal(row.repetitions, 3);
assert.equal(sm2.getDueItems(state, row.nextReview - 1, "2").length, 0);
assert.equal(sm2.getDueItems(state, row.nextReview, "2").length, 1);
assert.equal(sm2.getDueItems(state, row.nextReview, "1").length, 0, "code-specific questions stay within their selected vehicle code");
assert.equal(sm2.getStats(state, row.nextReview, "2").total, 1);
assert.ok(sm2.questionId({ questionId: "x".repeat(300) }).length <= 12, "stable question IDs stay compact");
assert.equal(sm2.getStats(state, row.nextReview, "2").daily.reduce((n,d)=>n+d.attempts,0), 4, "daily activity counts each unique answer event");
const shared = {}; sm2.recordAnswer(shared, { q: "Shared road rule", opts: ["A", "B"], ans: 0 }, true, t0, "shared");
assert.equal(sm2.getDueItems(shared, t0 + sm2.DAY, "1").length, 1, "shared questions remain available across codes");
const queueState = {};
const queueQ = { key: "existing-key", q: "Mirror check", opts: ["Check mirrors", "Guess"], ans: 0, ex: "Observe.", topic: "Observation", code: "2" };
const queued = sm2.recordToReview(queueState, queueQ, false, t0, "queue-event");
assert.equal(queueState.review.length, 1);
assert.equal(queueState.review[0].key, "existing-key");
assert.equal(queueState.review[0].due, t0 + sm2.DAY);
sm2.recordToReview(queueState, queueQ, true, t0 + sm2.DAY, "queue-event-2");
assert.equal(queueState.review[0].level, 1);
assert.equal(queueState.review[0].misses, 1, "successful recall does not erase prior lapse history");

const malformed = { sm2: { version: 1, items: { bad: { repetitions: -1, interval: -2, easeFactor: 0, nextReview: -1 } }, events: [] } };
assert.equal(sm2.ensure(malformed).items.bad, undefined);
const same = sm2.questionId({ q: "  STOP  ahead ", opts: ["Stop", "Go"], ans: 0 });
assert.equal(same, sm2.questionId({ q: "stop ahead", opts: ["Stop", "Go"], ans: 0 }), "identity is insensitive to spacing and case");
console.log("SM-2 scheduling, bounded intervals, due filtering, idempotency and malformed-state recovery passed.");
